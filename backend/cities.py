def _norm(name: str) -> str:
    return name.strip().lower().replace("ё", "е")


_BY_NAME = {_norm(name): (lat, lon) for name, lat, lon in CITIES}


def coordinates(name: str) -> tuple[float, float] | None:
    """Latitude and longitude of a city, or None if it is not in the table."""
    if not name:
        return None
    return _BY_NAME.get(_norm(name))
